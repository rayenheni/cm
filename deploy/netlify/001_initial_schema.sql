-- CMCB / Netlify + Supabase: experimental foundation, NOT a complete deployment.
-- Run only against a new, dedicated Supabase project after reviewing the setup.
-- This script deliberately fails if cmcb_private already exists; it never drops
-- or modifies an existing schema. No example passwords or real data are seeded.
BEGIN;
CREATE SCHEMA cmcb_private;
REVOKE ALL ON SCHEMA cmcb_private FROM PUBLIC, anon, authenticated;

CREATE TABLE cmcb_private.meta (
  key text PRIMARY KEY,
  value text NOT NULL
);
CREATE TABLE cmcb_private.admins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (email = lower(email))
);
CREATE TABLE cmcb_private.sessions (
  token_hash text PRIMARY KEY CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  admin_id bigint NOT NULL REFERENCES cmcb_private.admins(id) ON DELETE CASCADE,
  csrf_token text NOT NULL CHECK (csrf_token ~ '^[0-9a-f]{64}$'),
  expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_expiry ON cmcb_private.sessions(expires_at);
CREATE TABLE cmcb_private.articles (
  id text PRIMARY KEY CHECK (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  expertise_id text NOT NULL,
  image text NOT NULL DEFAULT '',
  status text NOT NULL CHECK (status IN ('draft', 'published')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);
CREATE TABLE cmcb_private.article_translations (
  article_id text NOT NULL REFERENCES cmcb_private.articles(id) ON DELETE CASCADE,
  lang text NOT NULL CHECK (lang IN ('fr', 'ar')),
  body jsonb NOT NULL,
  PRIMARY KEY (article_id, lang)
);
CREATE TABLE cmcb_private.reservations (
  id uuid PRIMARY KEY,
  idempotency_key uuid NOT NULL UNIQUE,
  payload_hash text NOT NULL CHECK (payload_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  consent_at timestamptz NOT NULL,
  status text NOT NULL CHECK (status IN ('new', 'contacted', 'closed')),
  name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL,
  domain text NOT NULL,
  urgency text NOT NULL CHECK (urgency IN ('normal', '48h', 'urgent')),
  message text NOT NULL,
  lang text NOT NULL CHECK (lang IN ('fr', 'ar'))
);
CREATE INDEX reservations_created ON cmcb_private.reservations(created_at DESC, id);
CREATE INDEX reservations_status ON cmcb_private.reservations(status);
CREATE TABLE cmcb_private.outbox (
  reservation_id uuid PRIMARY KEY REFERENCES cmcb_private.reservations(id) ON DELETE CASCADE,
  status text NOT NULL CHECK (status IN ('disabled', 'pending', 'sending', 'sent', 'failed')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_attempt_at timestamptz,
  last_error text,
  sent_at timestamptz
);
CREATE TABLE cmcb_private.rate_limits (
  key text PRIMARY KEY,
  hits integer NOT NULL CHECK (hits >= 0),
  reset_at timestamptz NOT NULL
);

-- Defense in depth: no browser role may use the schema, tables, or identity
-- sequences, even if a privileged user accidentally exposes the schema in the
-- Supabase API configuration. No public policies are created.
REVOKE ALL ON ALL TABLES IN SCHEMA cmcb_private FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA cmcb_private FROM PUBLIC, anon, authenticated;
ALTER TABLE cmcb_private.meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.article_translations ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.outbox ENABLE ROW LEVEL SECURITY;
ALTER TABLE cmcb_private.rate_limits ENABLE ROW LEVEL SECURITY;
COMMIT;
