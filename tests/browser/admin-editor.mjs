// Run only against an isolated development database; this creates a test article.
import { chromium as playwright } from '@playwright/test';
import chromium from '@sparticuz/chromium';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
const base = process.env.TEST_BASE_URL;
const envFile = process.env.TEST_ENV_FILE;
if (!base || !envFile) throw new Error('Set TEST_BASE_URL and TEST_ENV_FILE for an isolated test server.');
const env = Object.fromEntries(readFileSync(envFile, 'utf8').split(/\r?\n/).filter(l => /^[A-Z0-9_]+=/.test(l)).map(l => { const at=l.indexOf('='); return [l.slice(0,at),l.slice(at+1)]; }));
const title='Article test ' + randomUUID().slice(0,8);
const browser=await playwright.launch({executablePath:await chromium.executablePath(),args:chromium.args.filter(a=>!['--disable-web-security','--allow-running-insecure-content','--disable-site-isolation-trials'].includes(a)),headless:true});
try {
 const mobile = process.env.TEST_MOBILE === 'true';
 const page=await browser.newPage({viewport:mobile ? {width:390,height:844} : {width:1440,height:900}, isMobile:mobile, hasTouch:mobile}), errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://fonts.googleapis.com/**',r=>r.abort());
 await page.route('https://images.pexels.com/**',r=>r.fulfill({path:'tests/fixtures/remote-placeholder.jpg',contentType:'image/jpeg'}));
 await page.goto(base+'/#/admin');
 await page.getByLabel('Adresse e-mail').fill(env.ADMIN_EMAIL);
 await page.getByLabel('Mot de passe',{exact:true}).fill(env.ADMIN_PASSWORD);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await page.getByRole('button',{name:'Nouvel article'}).click();
 await page.locator('#article-form').waitFor();
 assert(page.url().endsWith('#/admin/articles/new')); assert.equal(await page.getByRole('dialog').count(),0);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.getByLabel('Titre *',{exact:true}).fill(title);
 page.once('dialog',d=>d.dismiss()); await page.getByRole('button',{name:'Retour aux articles'}).click();
 assert(page.url().endsWith('#/admin/articles/new')); assert.equal(await page.getByLabel('Titre *',{exact:true}).inputValue(),title);
 page.once('dialog',d=>d.accept()); await page.goBack(); await page.getByRole('button',{name:'Nouvel article'}).waitFor();
 await page.getByRole('button',{name:'Nouvel article'}).click();
 await page.getByLabel('Titre *',{exact:true}).fill(title);
 await page.getByLabel('Catégorie *',{exact:true}).fill('Droit des affaires');
 await page.getByLabel('Résumé *',{exact:true}).fill('Résumé de test');
 await page.getByLabel('Introduction *',{exact:true}).fill('Introduction de test');
 await page.getByLabel('Titre de section *').fill('Section de test');
 await page.getByLabel('Paragraphes — un par ligne *').fill('Paragraphe de test');
 await page.getByLabel('Image par lien HTTPS (facultative)').fill('https://images.pexels.com/example.jpg');
 await page.getByLabel('Ou téléverser une image').setInputFiles('tests/fixtures/remote-placeholder.jpg');
 await page.waitForFunction(() => /^\/media\/[a-f0-9]{32}\.jpg$/.test(document.querySelector('#article-image')?.value || ''));
 const imageUrl=await page.getByLabel('Image par lien HTTPS (facultative)').inputValue();
 await page.waitForFunction(() => document.querySelector('img[alt="Aperçu de l’image"]')?.naturalWidth > 0);
 const slug=await page.getByLabel('Identifiant / slug *').inputValue();
 await page.getByRole('button',{name:'Enregistrer le brouillon'}).click();
 await page.getByText(title,{exact:true}).waitFor();
 const row=page.locator('tr').filter({hasText:title}); await row.getByRole('button',{name:'Modifier'}).click();
 await page.locator('#article-form').waitFor(); assert(page.url().endsWith(`#/admin/articles/${slug}/edit`));
 await page.reload(); await page.locator('#article-form').waitFor();
 assert.equal(await page.getByLabel('Titre *',{exact:true}).inputValue(),title);
 assert.equal(await page.getByLabel('Image par lien HTTPS (facultative)').inputValue(),imageUrl);
 await page.getByLabel('Image par lien HTTPS (facultative)').fill('https://images.pexels.com/updated.jpg');
 await page.getByLabel('Titre *',{exact:true}).fill(title+' modifié');
 await page.getByRole('button',{name:'Enregistrer le brouillon'}).click();
 await page.getByText(title+' modifié',{exact:true}).waitFor();
 const updated=page.locator('tr').filter({hasText:title+' modifié'});
 await updated.getByRole('button',{name:'Modifier'}).click(); await page.locator('#article-form').waitFor();
 assert.equal(await page.getByLabel('Image par lien HTTPS (facultative)').inputValue(),'https://images.pexels.com/updated.jpg');
 await page.getByRole('button',{name:'Retour aux articles'}).click(); await updated.waitFor();
 await updated.getByRole('button',{name:'Supprimer'}).click(); await updated.getByRole('button',{name:'Confirmer'}).click();
 await page.getByText(title+' modifié',{exact:true}).waitFor({state:'detached'});
 await page.goto(base+'/#/admin/articles/introuvable/edit'); await page.getByText('Article introuvable.',{exact:false}).waitFor();
 await page.goto(base+'/#/admin/articles/new'); await page.locator('#article-form').waitFor();
 await page.getByLabel('Titre *',{exact:true}).fill('Modification non enregistrée');
 if (mobile) await page.getByRole('button',{name:'Ouvrir le menu'}).click();
 let dialogs=0; page.once('dialog',d=>{ dialogs++; void d.accept(); });
 await page.getByRole('button',{name:'Déconnexion'}).last().click();
 await page.getByRole('button',{name:'Se connecter',exact:true}).waitFor(); assert.equal(dialogs,1);
 assert.deepEqual(errors,[]);
 console.log('PASS React article pages: create, edit, reload, navigation guard, save, delete and missing article' + (mobile ? ' (mobile).' : '.'));
} finally { await browser.close(); }
