import { chromium as playwright } from '@playwright/test';
import chromium from '@sparticuz/chromium';
import { readFileSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
const suffix = randomUUID().slice(0,8);
const env = Object.fromEntries(readFileSync(process.env.TEST_ENV_FILE || '.env','utf8').trim().split('\n').filter(l=>l.includes('=')).map(l=>[l.slice(0,l.indexOf('=')),l.slice(l.indexOf('=')+1)]));
const browser = await playwright.launch({ executablePath: await chromium.executablePath(), args: chromium.args.filter(a => !['--disable-web-security','--allow-running-insecure-content','--disable-site-isolation-trials'].includes(a)), headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, ignoreHTTPSErrors: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.route('https://fonts.googleapis.com/**', route => route.fulfill({body:'',contentType:'text/css'}));
await page.route('https://images.pexels.com/**', route => route.fulfill({path:'tests/fixtures/remote-placeholder.jpg',contentType:'image/jpeg'}));
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5173';
try {
 await page.goto(base, {waitUntil:'networkidle'});
 await page.getByRole('link',{name:'Articles',exact:true}).first().click();
 await page.waitForFunction(()=>document.querySelectorAll('a[href^="#/articles/"]').length >= 4);
 await page.goto(base+'/#/contact');
 await page.getByLabel('Nom complet *').fill('Browser Client '+suffix);
 await page.getByLabel('Adresse e-mail *').fill('browser-'+suffix+'@example.com');
 await page.getByLabel('Domaine concerné *').selectOption('Droit des Affaires, des Sociétés & Commercial');
 await page.getByLabel('Votre situation *').fill('Demande de test navigateur pour vérifier la persistence serveur.');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Envoyer ma demande'}).click();
 await page.getByText('Votre demande a été enregistrée.').waitFor({timeout:8000}).catch(async e=>{console.log(await page.locator('form').innerText()); throw e;});
 await page.goto(base+'/#/admin');
 await page.getByLabel('Adresse e-mail').fill(env.ADMIN_EMAIL);
 await page.getByLabel('Mot de passe',{exact:true}).fill(env.ADMIN_PASSWORD);
 await page.getByRole('button',{name:'Se connecter'}).click();
 await page.getByRole('button',{name:'Réservations'}).last().click();
 await page.getByText('Browser Client '+suffix,{exact:false}).first().waitFor();
 await page.getByRole('button',{name:'Browser Client '+suffix}).first().click();
 await page.getByText('Demande de test navigateur pour vérifier la persistence serveur.').waitFor();
 await page.getByLabel('Statut de Browser Client '+suffix).first().selectOption('contacted');
 await page.waitForTimeout(500);
 await page.reload();
 await page.getByRole('button',{name:'Réservations'}).last().click();
 await page.getByLabel('Statut de Browser Client '+suffix).first().waitFor();
 assert.equal(await page.getByLabel('Statut de Browser Client '+suffix).first().inputValue(),'contacted');
 await page.getByRole('button',{name:'Articles'}).last().click();
 await page.getByRole('button',{name:'Nouvel article'}).click();
 await page.locator('#article-form').waitFor();
 assert(page.url().endsWith('#/admin/articles/new'));
 assert.equal(await page.getByRole('dialog').count(),0);
 await page.getByLabel('Titre *',{exact:true}).fill('Article test '+suffix);
 await page.getByLabel('Catégorie *',{exact:true}).fill('Droit des affaires');
 await page.getByLabel('Résumé *',{exact:true}).fill('Résumé de test');
 await page.getByLabel('Introduction *',{exact:true}).fill('Introduction de test');
 await page.getByLabel('Titre de section *').fill('Section de test');
 await page.getByLabel('Paragraphes — un par ligne *').fill('Paragraphe de test');
 await page.getByRole('button',{name:'Enregistrer le brouillon'}).click();
 await page.locator('#article-form').waitFor({state:'detached'});
 await page.getByText('Article test '+suffix,{exact:true}).first().waitFor();
 const publicContext = await browser.newContext();
 const publicPage = await publicContext.newPage();
 const response = await publicPage.request.get(base+'/api/articles?lang=fr');
 const body = await response.json();
 assert(!body.articles.some(a=>a.title==='Article test '+suffix));
 const requests = await page.request.get(base+'/api/admin/reservations');
 assert((await requests.json()).total >= 1);
 await page.getByRole('dialog').waitFor({state:'detached'});
 await page.getByRole('button',{name:'Sécurité'}).last().click();
 await page.getByText('SMTP non configuré.',{exact:false}).waitFor();
 mkdirSync('test-results',{recursive:true});
 await page.screenshot({path:'test-results/admin-security.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Browser smoke passed: public articles, real contact submission, admin login, cross-context server persistence, status reload, draft privacy, settings; no runtime errors.');
} finally { await browser.close(); }
